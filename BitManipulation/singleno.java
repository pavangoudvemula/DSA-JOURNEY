// LEETCODE PROBLEM 136. Single Number
// APPROACH : XOR OF TWO SAME NUMBERS WILL BE ZERO SO THE ARRAY CONTAINS ALL ELEMENTS ARE REPEATED BY TWICE AND ONE NUMBER IS EXACTLY ONE 
// WHEN WE DO XOR OF THOSE ATOMATICALLY EVERY NUMBER WHICH IS REPATEING TWICE WILLL BE CANCELED  OUT EACH OTHER REMAINS ONLY THE NUMBER WHICH IS REPAETED ONLY ONE TIMES
// TIME COMPLEXITY : O(N)
// SPACE COMPLEXITY: O(1)
class Solution {
    public int singleNumber(int[] nums) {
        int ans=0;
        for(int x: nums){
            ans ^=x;
        }
        return ans;
        
    }
}