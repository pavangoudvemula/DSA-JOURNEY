/* APPROACH 1: IF A  NUMBER IS POWER OF TWO THAT MEANS IT CONTAINS ONLY ONE SET BIT IN  ITS BINARY REPRESENTAION 
 SO WE FOR A GIVEN N WE CAN COUNT NO OF SET BITS FOR THAT NUMBER IF IT IS EQUAL TO ONE THEN IT IS POWER OF TWO ELSE IT IS NOT */

/*  APPRAOCH 2: FOR A GIVEN N WE DO BITWISE AND  WITH (N-1)  IF IT ZERO THE NUMBER IS POWER OF TWO ELSE IT IS NOT 
WHY IT WORKS BECAUSE WHEN WE DO N&(N-1) IT REMOVES RIGHT MOST SET BIT  
IF IT IS POWER OF TWO THAT MEANS IT CONTAINS ONLY 1 SET BIT AND 
IT REMOVES IT GIVE THE RESULT AS 0 IF IT IS NOT POWER OF 2  THEN IT WILL GIVE NON ZERO VALUE */




class Solution {
    public boolean isPowerOfTwo(int n) {
        if(n>0 && (n&(n-1))==0){
            return true;

        }
        return false;
        
    }
}